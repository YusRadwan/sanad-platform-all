<?php

declare(strict_types=1);

namespace App\Actions\Teacher;

use App\Models\Teacher;

/**
 * Replaces a teacher's ENTIRE social-link set with the supplied rows.
 *
 * Port of backend/TeacherRepository::replaceSocialLinks(). Delete-and-reinsert,
 * not a diff, because THE PAYLOAD IS THE COMPLETE DESIRED SET: AddTeacher.tsx
 * sends every platform the admin left enabled, so a link the admin switched off
 * must DISAPPEAR — and there is no stable client-side row id to diff against
 * (the form's state is keyed by platform name, not by id).
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ THIS MUST RUN INSIDE THE CALLER'S TRANSACTION.                          │
 * │                                                                          │
 * │ Between the delete and the insert the teacher has NO social links. Both  │
 * │ callers (CreateTeacher, UpdateTeacher) wrap it in DB::transaction(), so  │
 * │ that window is never observable — a concurrent read of the public        │
 * │ profile sees the old set or the new set, never the empty middle.         │
 * │ There is deliberately no transaction of its own here: nesting one would  │
 * │ open a savepoint that commits independently of the caller's rollback,    │
 * │ which is precisely the guarantee being relied on.                        │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * AN EMPTY $rows IS A LEGITIMATE INSTRUCTION, NOT A NO-OP: it is how the admin
 * removes every link. The delete still runs; only the insert is skipped.
 * (Whether an empty array even reaches here is the CALLER's decision — see
 * UpdateTeacher's has()-vs-filled() note.)
 *
 * @phpstan-type LinkRow array{platform: string, url: string, enabled: bool, order_index: int}
 */
final class ReplaceSocialLinks
{
    /**
     * @param list<array{platform: string, url: string, enabled: bool, order_index: int}> $rows
     */
    public function __invoke(Teacher $teacher, array $rows): void
    {
        $teacher->socialLinks()->delete();

        if ($rows === []) {
            return;
        }

        // createMany, not insert(): the ids are UUIDs generated by HasUuids on
        // the model, and a raw builder insert would bypass that and violate the
        // CHAR(36) primary key's NOT NULL.
        $teacher->socialLinks()->createMany($rows);

        // The relation was just mutated behind the loaded collection's back;
        // anything presenting this teacher in the same request must see the new
        // set, not the stale one it loaded before the write.
        $teacher->unsetRelation('socialLinks');
    }
}
