    'channels' => [

        /*
         * ------------------------------------------------------------------
         * The two channels this application actually uses
         * ------------------------------------------------------------------
         *
         * Ported 1:1 from backend/app/Core/Logger.php, which hand-rolled a
         * static two-channel file logger because the old codebase had no
         * dependency to do it with. Laravel's `daily` driver is that same
         * behaviour as a first-party feature — including the rotation the
         * old logger only approximated by putting the date in the filename
         * and never deleting anything.
         *
         * The filenames are preserved exactly, because they are the operator-
         * facing contract (deploy runbooks, log shipping, grep habits):
         *   storage/logs/app-YYYY-MM-DD.log
         *   storage/logs/security-YYYY-MM-DD.log
         * Laravel's daily driver appends "-Y-m-d" to the basename, so a path
         * of `logs/app.log` produces `app-2026-08-03.log`.
         */

        'app' => [
            'driver' => 'daily',
            'path' => storage_path('logs/app.log'),
            'level' => env('LOG_LEVEL', 'debug'),
            'days' => env('LOG_DAILY_DAYS', 14),
            'replace_placeholders' => true,
        ],

        /*
         * Authentication and authorisation events. Nothing writes here in
         * Stage 0 by design — there is no auth yet — but the channel is stood
         * up now because App\Exceptions\Handler already routes 401/403 to it,
         * and Stage 1's login/logout/session events will land here with no
         * further configuration.
         */
        'security' => [
            'driver' => 'daily',
            'path' => storage_path('logs/security.log'),
            'level' => env('LOG_SECURITY_LEVEL', 'info'),
